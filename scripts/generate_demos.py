#!/usr/bin/env python3
"""Generate ~20s TTS demos and run STT backends over them."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from arabic_voice.paths import OUTPUTS_DIR, SCRIPTS_DIR, ensure_dirs  # noqa: E402
from arabic_voice.registry import get_backend  # noqa: E402
from arabic_voice.stt.registry import get_stt_backend, list_stt_backend_ids  # noqa: E402
from arabic_voice.stt.types import TranscriptionRequest  # noqa: E402
from arabic_voice.types import SynthesisRequest  # noqa: E402

# ~20s of Emirati / Gulf speech when spoken at natural pace
DEMO_TEXT = (
    "أهلًا، شحالك؟ تقدر تساعدني أحجز موعد؟ "
    "ترا الدرب صوب دبي اليوم وايد زحمة، خلنا نطلع بدري. "
    "السعر ألف وخمس مية درهم، والكود متاح بعد باچر. "
    "هني المكتب، تفضل اقعد، تبي قهوة عربية ولا شاهي؟ "
    "السلام عليكم، معاك المساعد الآلي لبنك الإمارات. كيف أقدر أخدمك؟"
)

TTS_BACKENDS = ["piper_emirati", "audar_flash", "habibi_uae"]
# Skip jais_asr by default (often OOM / multi-GB download on laptop Macs)
ASR_BACKENDS = [
    "whisper_baseline",
    "whisper_gulf_small",
    "whisper_arabic_ft",
    "wav2vec_emirati",
    "audar_asr_flash",
    "qwen_asr_uae",
]


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def generate_tts(dest: Path) -> list[Path]:
    dest.mkdir(parents=True, exist_ok=True)
    _write(dest / "prompt.txt", DEMO_TEXT + "\n")
    wavs: list[Path] = []
    notes: list[str] = ["# TTS demo (~20s Emirati)", "", f"Prompt: {DEMO_TEXT}", ""]

    refs = ROOT / "assets" / "refs"
    ref_audio = refs / "uae_ref.wav"
    ref_text = (refs / "uae_ref.txt").read_text(encoding="utf-8").strip() if (refs / "uae_ref.txt").exists() else None

    for bid in TTS_BACKENDS:
        print(f"\n=== TTS {bid} ===")
        try:
            b = get_backend(bid, reload=True)
            b.ensure_loaded()
            req = SynthesisRequest(
                text=DEMO_TEXT,
                ref_audio=ref_audio if ref_audio.exists() else None,
                ref_text=ref_text,
            )
            result = b.synthesize(req)
            out = dest / f"{bid}.wav"
            result.write_wav(out)
            dur = len(result.audio) / float(result.sample_rate)
            print(f"OK {out} ({dur:.1f}s)")
            notes.append(f"- `{bid}.wav` — {dur:.1f}s @ {result.sample_rate} Hz")
            wavs.append(out)
        except Exception as exc:
            print(f"FAIL {bid}: {exc}")
            notes.append(f"- `{bid}` — FAILED: {exc}")
            _write(dest / f"{bid}.error.txt", str(exc) + "\n")

    notes.extend(
        [
            "",
            "Listen order: piper_emirati → audar_flash → habibi_uae (NC).",
            "Generated by `scripts/generate_demos.py`.",
        ]
    )
    _write(dest / "README.md", "\n".join(notes) + "\n")
    return wavs


def generate_asr(dest: Path, audio: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    _write(dest / "audio_source.txt", str(audio.resolve()) + "\n")
    notes = [
        "# ASR demo",
        "",
        f"Source audio: `{audio.relative_to(ROOT)}`",
        "",
        "Transcripts:",
        "",
    ]

    known = set(list_stt_backend_ids())
    for bid in ASR_BACKENDS:
        if bid not in known:
            continue
        print(f"\n=== ASR {bid} ===")
        try:
            b = get_stt_backend(bid, reload=True)
            b.ensure_loaded()
            result = b.transcribe(TranscriptionRequest(audio=audio, language="ar"))
            out = dest / f"{bid}.txt"
            result.write_text(out)
            print(f"OK {out}")
            print(result.text[:160])
            notes.append(f"### `{bid}`\n\n{result.text.strip()}\n")
        except Exception as exc:
            print(f"FAIL {bid}: {exc}")
            notes.append(f"### `{bid}`\n\nFAILED: {exc}\n")
            _write(dest / f"{bid}.error.txt", str(exc) + "\n")

    notes.append("\nGenerated by `scripts/generate_demos.py`.\n")
    _write(dest / "README.md", "\n".join(notes))


def main() -> int:
    ensure_dirs()
    tts_dir = OUTPUTS_DIR / "tts_demo"
    asr_dir = OUTPUTS_DIR / "asr_demo"

    wavs = generate_tts(tts_dir)
    if not wavs:
        # fall back to concatenating prompt lines via piper only already attempted
        print("No TTS WAV produced; cannot run ASR demo.")
        return 1

    # Prefer piper for ASR source (most reliable on Mac)
    source = next((w for w in wavs if w.name.startswith("piper")), wavs[0])
    generate_asr(asr_dir, source)
    print(f"\nDone.\n  TTS → {tts_dir}\n  ASR → {asr_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
